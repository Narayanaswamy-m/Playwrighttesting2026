
// The nullish coalescing operator (??) returns the right-hand value only when the left-hand value is:

// null
// undefined

// Otherwise, it returns the left-hand value.

let name = null;

console.log(name ?? "Guest"); // guest 

let name1 = "Narayan";

console.log(name1 ?? "Guest");  // Narayan

